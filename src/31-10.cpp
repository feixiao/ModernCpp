// ============================================================================
// 【说明】：演示 C++17 [[maybe_unused]] 属性消除未引用变量/形参警告。
// 【重点】：
//   1. foo(int a [[maybe_unused]], ...) 抑制未用形参 -Wunused-parameter 告警
//   2. 常用在仅供断言（assert）消费的调试参数或预留接口参数中
// ============================================================================
int foo(int a [[maybe_unused]], int b [[maybe_unused]])
{
	return 5;
}

int main()
{
	foo(1, 2);
}
