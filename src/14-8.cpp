// ============================================================================
// 【说明】：演示 C++17 放宽有固定底层类型的 enum class 的列表初始化语法规则。
// 【重点】：
//   1. C++17 允许 Color c{ 5 }; 直接列表初始化强类型枚举（无需显式类型转换）
//   2. 仍禁止赋值隐式转换（Color c1 = 5; 报错）或拷贝列表初始化（Color c2 = {5}; 报错）
// ============================================================================
enum class Color {
	Red,
	Green,
	Blue
};
int main()
{
	Color c{ 5 };		// 编译成功
	Color c1 = 5;		// 编译失败
	Color c2 = { 5 };	// 编译失败
	Color c3(5);		// 编译失败
}
