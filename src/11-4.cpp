// ============================================================================
// 【说明】：演示非受限联合体未初始化成员导致未定义行为（UB）的错误示例。
// 【重点】：
//   1. 联合体默认初始化了 x3，但随后直接向未初始化的 x4 (vector) 调用 push_back
//   2. 属于未构造对象的非法访问，展示联合体需要手动维护当前活跃类型的缺陷
// ============================================================================
#include <iostream>
#include <string>
#include <vector>

union U
{
	U() : x3() {}
	~U() { x3.~basic_string(); }
	int x1;
	float x2;
	std::string x3;
	std::vector<int> x4;
};

int main()
{
	U u;
	u.x4.push_back(58);
}
