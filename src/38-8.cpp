// ============================================================================
// 【说明】：演示 C++17 聚合类模板上的聚合初始化实参推导。
// 【重点】：
//   1. struct S { T x; T y; }; 无显式构造函数
//   2. S s1{ 1, 2 }; 编译器基于聚合初始化列表自动推导 T 为 int
// ============================================================================
template <class T>
struct S {
	T x;
	T y;
};

S s1{ 1, 2 }; //编译成功 S<int>
S s2{ 1, 2u }; // 编译失败
