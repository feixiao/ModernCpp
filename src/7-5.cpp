// ============================================================================
// 【说明】：演示混合值捕获与引用捕获，结合 mutable 在多次调用间的状态保留。
// 【重点】：
//   1. [x, &y]() mutable 中，x 是闭包对象内部持有的独立状态（多次调用累加），外部 x 保持 5 不变
//   2. &y 是引用捕获，Lambda 内部递增会直接同步修改外部的实参 y
// ============================================================================
#include <iostream>

int main()
{
    int x = 5, y = 8;
    auto foo = [x, &y]() mutable {
        x += 1;
        y += 2;
        std::cout << "lambda x = " << x << ", y = " << y << std::endl;
        return x * y;
    };
    foo();
    std::cout << "call1  x = " << x << ", y = " << y << std::endl;
    foo();
    std::cout << "call2  x = " << x << ", y = " << y << std::endl;
}
