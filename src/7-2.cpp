// 【说明】：演示 Lambda 捕获规则对全局变量与静态局部变量的限制（编译错误示例）。
// 【重点】：
//   1. 全局变量（x）与静态局部变量（static int z）拥有静态存储期，Lambda 内可直接访问
//   2. 它们无需也不允许被显式写入捕获列表 [x, y, z]，否则会导致编译报错
//   3. 捕获列表只用于捕获自动存储期（局部非静态）变量
// ============================================================================
int x = 0;

int main()
{
    int y = 0;
    static int z = 0;
    auto foo = [x, y, z] {};
}
