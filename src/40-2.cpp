// ============================================================================
// 【说明】：演示基于可变参数省略号（...）兜底备选的 SFINAE 重载优先级匹配。
// 【重点】：
//   1. foo(T& t) 优先匹配左值引用
//   2. 传入右值 foo(5) 无法绑定非常量左值引用，主模板替换失败后平滑回退到 void foo(...) 兜底
// ============================================================================
template<class T>
T foo(T& t)
{
	T tt(t);
	return tt;
}

void foo(...) {}

int main()
{
	double x = 7.0;
	foo(x);
	foo(5);
}
