// ============================================================================
// 【说明】：演示 C++11 放宽模板实参允许使用局部类型与未命名类型。
// 【重点】：
//   1. C++03 禁止局部类型（struct A）或未命名类型（enum { e1 }）实例化模板
//   2. C++11 废除该限制，X<A> 和 X<B> 完全合法
// ============================================================================
template <class T> class X { };
template <class T> void f(T t) { }
struct {} unnamed_obj;

int main()
{
	struct A { };
	enum { e1 };
	typedef struct {} B;
	B b;
	X<A>  x1;		// C++11编译成功，C++03编译失败
	X<A*> x2;		// C++11编译成功，C++03编译失败
	X<B>  x3;		// C++11编译成功，C++03编译失败
	f(e1);			// C++11编译成功，C++03编译失败
	f(unnamed_obj); // C++11编译成功，C++03编译失败
	f(b);			// C++11编译成功，C++03编译失败
}
