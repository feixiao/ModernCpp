// ============================================================================
// 【说明】：演示 Lambda 正确访问全局变量、静态局部变量与局部变量的方式。
// 【重点】：
//   1. 局部变量 y 放入捕获列表 [y] 按值捕获
//   2. 全局变量 x 和静态变量 z 无需捕获，直接在 Lambda 函数体中使用
// ============================================================================
#include <iostream>

int x = 1;
int main()
{
    int y = 2;
    static int z = 3;
    auto foo = [y] { return x + y + z; };
    std::cout << foo() << std::endl;
}
