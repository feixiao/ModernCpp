// ============================================================================
// 【说明】：演示传统 C++ 对指针非类型模板参数链接性（Linkage）的限制。
// 【重点】：
//   1. C++03 要求指针模板实参必须具备外部链接性（extern char str1[]）
//   2. 内部链接的 const char str2[] 在旧标准下会引发报错，C++11/17 逐步放宽
// ============================================================================
template<const char *> struct Y {};
extern const char str1[] = "hello world"; // 外部连接
const char str2[] = "hello world"; // 内部连接

int main()
{
	Y<str1> y1;
	Y<str2> y2;
}
