// ============================================================================
// 【说明】：演示 C++ 中左值（lvalue）与右值（rvalue）的基本概念与表达式值类别。
// 【重点】：
//   1. ++x 是左值表达式（返回变量自身引用，可继续赋值或取地址）
//   2. x++ 是纯右值（prvalue，返回递增前的临时副本值，不可赋值）
//   3. get_val() 返回临时值（右值），set_val(6) 接收右值传参
// ============================================================================
int x = 1;

int get_val()
{
	return x;
}

void set_val(int val)
{
	x = val;
}

int main() 
{
	x++;
	++x;
	int y = get_val();
	set_val(6);
}
