// 【说明】：演示约束表达式因语法结构微调（如乘法操作数次序）导致原子约束无法判等引发的二义性报错。
// 【重点】：
//   1. Add1<2 * N> 与 Add1<N * 2> 虽然数学等价，但在编译器原子约束比对时被视作不同表达式
//   2. 导致两分支无法决出更特化的偏序关系，调用时报二义性编译失败
// ============================================================================
template <int N> void f2()
requires Add1<2 * N> {};
template <int N> void f2()
requires Add1<N * 2> && true {};

f2<0>(); // 编译失败
