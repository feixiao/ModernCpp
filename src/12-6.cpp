// ============================================================================
// 【说明】：演示委托构造中禁止环形委托（Cyclic Delegation）的规则。
// 【重点】：
//   1. 若 X() 委托 X(0)，而目标构造函数又反向委托 X()，将形成无限递归环路
//   2. 编译器会在编译期检查并报错递归委托
// ============================================================================
class X
{
public:
	X() : X(0) {}
	X(int a) : X(a, 0.) {}
	X(double b) : X(0, b) {}
	X(int a, double b) : X() { CommonInit(); }

private:
	void CommonInit() {}
	int a_;
	double b_;
};
