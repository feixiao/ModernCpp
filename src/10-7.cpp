// ============================================================================
// 【说明】：演示 C++11 = delete 不仅适用于类成员函数，也可用于普通全局与静态函数。
// 【重点】：
//   1. void foo() = delete; static void bar() = delete;
//   2. 被 delete 的全局函数参与重载决议但无法被调用，触发编译失败
// ============================================================================
void foo() = delete;
static void bar() = delete;
int main()
{
	bar();		// 编译失败，函数已经被显式删除
	foo();		// 编译失败，函数已经被显式删除
}
