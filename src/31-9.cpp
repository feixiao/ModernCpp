// ============================================================================
// 【说明】：演示 C++20 允许将 [[nodiscard]] 直接应用于构造函数。
// 【重点】：
//   1. [[nodiscard]] X() 要求构造出来的临时对象不能被立即就地遗弃
//   2. 如构造无名临时对象 X{}; 会触发编译器告警，强制其必须绑定到具名变量
// ============================================================================
class X {
public:
	[[nodiscard]] X() {}
	X(int a) {}
};

int main()
{
	X x;
	X{};
	X{ 42 };
}
