// ============================================================================
// 【说明】：演示 Lambda 闭包捕获发生的时间点（定义时捕获 vs 调用时求值）。
// 【重点】：
//   1. 值捕获变量 x 在 Lambda 定义那一刻完成拷贝（记录快照 5）
//   2. 后续外部将 x 改为 9 不会影响闭包内部的 x；但引用捕获 y 依然映射外部最新变量（20）
// ============================================================================
#include <iostream>

int main()
{
    int x = 5, y = 8;
    // 定义 Lambda 时，x 的值被捕获为 5，y 被按引用捕获
    // 此时闭包内部的 x 已经是 5 的副本，y 是对外部 y 的引用
    // 此时闭包内部的 x 是 5 的副本，后续对外部 x 的修改不会影响闭包内部的 x
    // 而 y 是引用捕获，闭包内部对 y 的修改会影响外部 y
    auto foo = [x, &y]() mutable {
        x += 1;
        y += 2;
        std::cout << "lambda x = " << x << ", y = " << y << std::endl;
        return x * y;
    };
    x = 9;
    y = 20;
    foo();
}
