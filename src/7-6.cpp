// ============================================================================
// 【说明】：演示 Lambda 闭包捕获发生的时间点（定义时捕获 vs 调用时求值）。
// 【重点】：
//   1. 值捕获变量 x 在 Lambda 定义那一刻完成拷贝（记录快照 5）
//   2. 后续外部将 x 改为 9 不会影响闭包内部的 x；但引用捕获 y 依然映射外部最新变量（20）
// ============================================================================
#include <iostream>

int main()
{
    int x = 5, y = 8;
    auto foo = [x, &y]() mutable {
        x += 1;
        y += 2;
        std::cout << "lambda x = " << x << ", y = " << y << std::endl;
        return x * y;
    };
    x = 9;
    y = 20;
    foo();
}
