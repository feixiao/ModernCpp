// ============================================================================
// 【说明】：演示 C++98 传统通过声明 private 成员函数来“禁用”特定接口的缺陷。
// 【重点】：
//   1. 将 void foo(long&) 声明为私有试图禁止调用
//   2. 外部传入 long 变量调用 b.foo(l) 时，重载决议依然先选定最佳匹配的 private 成员，导致编译报“访问私有成员”错误
// ============================================================================
class Base {
	void foo(long &);
public:
	void foo(int) {}
};

int main()
{
	Base b;
	long l = 5;
	b.foo(8);
	b.foo(l);       // 编译错误
}
