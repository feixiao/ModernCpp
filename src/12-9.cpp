// ============================================================================
// 【说明】：演示目标构造函数执行完毕后抛出异常时的对象析构行为。
// 【重点】：
//   1. 在 C++ 中，目标构造函数完成的那一刻起，该对象即视为已完全构造成功
//   2. 后续委托构造函数体抛出异常时，编译器会调用该对象的析构函数清理已初始化的资源
// ============================================================================
#include <iostream>

class X
{
public:
	X() : X(0, 0.) { throw 1; }
	X(int a) : X(a, 0.) {}
	X(double b) : X(0, b) {}
	X(int a, double b) : a_(a), b_(b) { CommonInit(); }
	~X() { std::cout << "~X()" << std::endl; }
private:
	void CommonInit() {}
	int a_;
	double b_;
};

int main()
{
	try {
		X x;
	}
	catch (...) {
	}
}
