// ============================================================================
// 【说明】：演示 C++11 统一列表初始化（List-initialization）的直接初始化与复制初始化形式。
// 【重点】：
//   1. 大括号 {} 可以统一用于内置类型、自定义类型、函数实参、函数返回值及 new 表达式
//   2. 直接初始化：如 int x1{8}; C x3{2};
//   3. 复制初始化：如 int x = {5}; C x2 = {4}; foo({8}); return {"world", 5};
// ============================================================================
#include <string>

struct C {
	C(std::string a, int b) {}
	C(int a) {}
};

void foo(C) {}
C bar()
{
	return {"world", 5};
}

int main()
{
	int x = {5};            // 复制初始化
	int x1{8};              // 直接初始化
	C x2 = {4};             // 复制初始化
	C x3{2};                // 直接初始化
	foo({8});               // 复制初始化
	foo({"hello", 8});      // 复制初始化
	C x4 = bar();           // 复制初始化
	C *x5 = new C{ "hi", 42 };  // 直接初始化
}
