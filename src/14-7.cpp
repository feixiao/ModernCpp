// ============================================================================
// 【说明】：演示 C++11 同样允许传统 unscoped enum 显式指定底层类型。
// 【重点】：
//   1. enum E : unsigned int 明确指定底层存储
//   2. 虽然不具备强类型隔离，但获得了确定的大小和允许前置声明的优势
// ============================================================================
enum E : unsigned int {
    e1 = 1,
    e2 = 2,
    e3 = 0xfffffff0
};

int main()
{
    bool b = e1 < e3;
    std::cout << std::boolalpha << b << std::endl;
}
