// ============================================================================
// 【说明】：演示 C++17 [[nodiscard]] 属性强制要求检查函数返回值或类实例。
// 【重点】：
//   1. 标记在函数 [[nodiscard]] int foo() 或类 class [[nodiscard]] X
//   2. 调用者丢弃返回值时，编译器抛出警告，防止忽略关键错误码或 RAII 守护对象
// ============================================================================
class [[nodiscard]] X {};

[[nodiscard]] int foo() { return 1; }
X bar() { return X(); };

int main()
{
	X x;
	foo();
	bar();
}
