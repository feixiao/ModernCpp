// ============================================================================
// 【说明】：演示具有显式底层类型的枚举直接列表初始化的成功场景。
// 【重点】：
//   1. Color1 指定底层 char，Color2 指定 short
//   2. C++17 下 Color1 c{ 7 }; 与 Color2 c1{ 11 }; 均合法编译
// ============================================================================
enum class Color1 : char {};
enum Color2 : short {};

int main()
{
	Color1 c{ 7 };
	Color2 c1{ 11 };
	Color2 c2 = Color2{ 5 };
}
