// ============================================================================
// 【说明】：演示 [[nodiscard]] 类型在函数返回引用时不触发未消费警告的例外场景。
// 【重点】：
//   1. 当函数返回引用 X& bar(X &x) 时，未消费该引用通常代表仅就地操作原对象，不会触发告警
// ============================================================================
class[[nodiscard]] X{};
X& bar(X &x) { return x; };

int main()
{
	X x;
	bar(x);	// bar返回引用，nodiscard不起作用，不会引发警告
}
