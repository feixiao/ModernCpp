// ============================================================================
// 【说明】：演示 C++11 泛型函数中利用尾置返回类型配合 decltype 推导相加结果类型。
// 【重点】：
//   1. 函数形参 t1, t2 在前置返回值位置尚未引入作用域，不能写 decltype(t1+t2) sum(...)
//   2. 尾置写法 auto sum(...) -> decltype(t1 + t2) 可以合法引用入参名称进行推导
// ============================================================================
template<class T1, class T2>
auto sum1(T1 t1, T2 t2)->decltype(t1 + t2)
{
	return t1 + t2;
}

int main() {
	auto x1 = sum1(4, 2);
}
