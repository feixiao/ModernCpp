// ============================================================================
// 【说明】：演示 C++20 [[likely]] 和 [[unlikely]] 属性指导分支预测（Branch Prediction）。
// 【重点】：
//   1. [[unlikely]] case 2: 指导编译器该分支命中概率极低
//   2. 优化生成的汇编跳转分支布局，减少高频热点执行路径的流水线停顿
// ============================================================================
int f(int i) {
    switch(i) {
    case 1: return 1;
    [[unlikely]] case 2: return 2;
    }
    return 3;
}
