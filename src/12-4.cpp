// ============================================================================
// 【说明】：演示链式委托构造（形成委托调用链）的实现方式。
// 【重点】：
//   1. X() 委托给 X(0)，X(0) 进一步委托给目标构造函数 X(0, 0.)
//   2. 使得不同复杂度的构造函数可以逐级组装默认值
// ============================================================================
class X
{
public:
	X() : X(0) {}
	X(int a) : X(a, 0.) {}
	X(double b) : X(0, b) {}
	X(int a, double b) : a_(a), b_(b) { CommonInit(); }
private:
	void CommonInit() {}
	int a_;
	double b_;
};
