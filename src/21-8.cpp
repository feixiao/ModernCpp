// ============================================================================
// 【说明】：演示带 noexcept 的函数指针可以隐式转换为普通不带 noexcept 的函数指针（逆向兼容）。
// 【重点】：
//   1. void(*fp)() 是普通函数指针，void foo() noexcept 是更强保证的函数
//   2. 更安全的类型可以安全隐式退化并赋值给较弱保证的函数指针
// ============================================================================
void(*fp)() = nullptr;
void foo() noexcept {}

int main()
{
	fp = &foo;
}
