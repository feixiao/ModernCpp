// ============================================================================
// 【说明】：演示 constexpr 常量及 constexpr 函数返回值作为非类型模板实参。
// 【重点】：
//   1. X<v> 与 X<foo()>
//   2. 只要是在编译期确定的常量表达式，均可直接作为整型非类型模板参数
// ============================================================================
constexpr char v = 42;
constexpr char foo() { return 42; }
template<int> struct X {};

int main()
{
	X<v> x1;
	X<foo()> x2;
}
