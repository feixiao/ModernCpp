// ============================================================================
// 【说明】：演示委托构造函数不能在初始化列表中同时初始化成员变量的语法约束（编译错误）。
// 【重点】：
//   1. X(int a) : X(), a_(a) {} 会导致编译报错
//   2. 语法规定：一旦在初始化列表中调用了委托构造函数，就不能再初始化其他数据成员
// ============================================================================
class X
{
public:
	X() : a_(0), b_(0) { CommonInit(); }
	X(int a) : X(), a_(a) {}		// 编译错误，委托构造函数不能在初始化列表初始化成员变量
	X(double b) : X(), b_(b) {}	    // 编译错误，委托构造函数不能在初始化列表初始化成员变量

private:
	void CommonInit() {}
	int a_;
	double b_;
};
