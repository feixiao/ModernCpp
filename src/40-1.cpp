// ============================================================================
// 【说明】：演示 C++98 经典 SFINAE（匹配失败不是错误）原理：通过 sizeof(foo(...)) 在编译期做类型探测。
// 【重点】：
//   1. 利用两个不同返回大小的函数重载（char vs double）
//   2. 在模板实例化替换时若某个候选签名不合法，编译器静默剔除该候选而非报错中断
// ============================================================================
template <int I> struct X {};

char foo(int);
char foo(float);

template <class T> X<sizeof(foo((T)0))> f(T)
{
	return X<sizeof(foo((T)0))>();
}

int main()
{
	f(1);
}
