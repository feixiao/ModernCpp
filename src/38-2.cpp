// ============================================================================
// 【说明】：演示结合 auto N 非类型推导与数组引用的泛型结构体。
// 【重点】：
//   1. template<class T, auto N> struct X { X(T(&)[N]) {} };
//   2. 自动捕获元素类型与数组长度
// ============================================================================
template<class T, auto N>
struct X
{
	X(T(&)[N]) {}
};

int main()
{
	X x("hello");
}
