// ============================================================================
// 【说明】：演示带参数的 requires 表达式：检查二元操作（+）是否支持。
// 【重点】：
//   1. concept C = requires (T a, T b) { a + b; };
//   2. 声明虚构的局部变量 a, b 检查特定操作符有效性
// ============================================================================
template<typename T> concept C =
requires (T a, T b) {
	a + b;
};
