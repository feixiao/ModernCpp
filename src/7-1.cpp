// ============================================================================
// 【说明】：演示 C++11 Lambda 表达式的基本语法与值捕获使用。
// 【重点】：
//   1. 语法构成：[捕获列表](形参列表) -> 返回类型 { 函数体 }
//   2. [x] 按值捕获局部变量 x，在闭包对象生成时保存副本
//   3. 调用 foo(8) 执行 lambda 并返回计算结果
// ============================================================================
#include <iostream>

int main()
{
    int x = 5;
    // 按值捕获局部变量 x，在闭包对象生成时保存副本
    auto foo = [x](int y)->int { return x * y; };
    std::cout << foo(8) << std::endl;
}
