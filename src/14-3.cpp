// ============================================================================
// 【说明】：演示传统枚举底层类型不确定导致的枚举值比较异常（符号/溢出陷阱）。
// 【重点】：
//   1. 传统 enum 未指定底层类型，编译器视数值范围选择 int 或 unsigned int
//   2. 0xfffffff0 导致比较逻辑可能因符号扩展产生违反直觉的结果
// ============================================================================
enum E {
 e1 = 1,
 e2 = 2,
 e3 = 0xfffffff0
};

int main()
{
 bool b = e1 < e3;
 std::cout << std::boolalpha << b << std::endl;
}
