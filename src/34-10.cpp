// ============================================================================
// 【说明】：演示未知边界数组引用与已知定长数组引用的重载决议优先级规则。
// 【重点】：
//   1. f(int(&)[]) 与 f(int(&)[1]) 同时存在时
//   2. 传入 arr[1] 优先精确匹配定长特化重载版本 f(int(&)[1])
// ============================================================================
#include <iostream>
void f(int(&)[])
{
	std::cout << "call f(int(&)[])";
}
void f(int(&)[1])
{
	std::cout << "call f(int(&)[1])";
}
int arr[1];

int main()
{
	f(arr);
}
