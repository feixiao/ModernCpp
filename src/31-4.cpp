// ============================================================================
// 【说明】：演示 C++14 [[deprecated]] 属性标记废弃函数与废弃类。
// 【重点】：
//   1. 标记弃用的函数（foo()）或类型（class X）被使用时，编译器会触发弃用告警
//   2. 用于向后兼容的类库渐进式 API 淘汰
// ============================================================================
[[deprecated]] void foo() {}
class [[deprecated]] X {};
int main()
{
	X x;
	foo();
}
