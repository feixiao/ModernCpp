// ============================================================================
// 【说明】：演示空形参包在逻辑与（&&）折叠表达式下的标准默认单位元值。
// 【重点】：
//   1. 对空包执行 (args && ...) 时，C++17 规定其默认值为 true
//   2. 对 (args || ...) 空包默认为 false；对逗号运算符空包默认为 void()
// ============================================================================
#include <iostream>

template<typename... Args>
auto andop(Args... args)
{
	return (args && ...);
}

int main()
{
	std::cout << std::boolalpha << andop();
}
