// ============================================================================
// 【说明】：演示通过默认参数合并多个构造函数的传统做法及其局限性。
// 【重点】：
//   1. 默认实参构造函数在参数组合较为固定时可行
//   2. 当重载构造逻辑差异较大、非单纯缺省参数时，无法完全替代构造函数分工
// ============================================================================
class X4
{
public:
	X4(int c) : a_(0), b_(0.), c_(c) { CommonInit(); }
	X4(double b) : a_(0), b_(b), c_(0) { CommonInit(); }
	X4(int a = 0, double b = 0., int c = 0) : a_(a), b_(b), c_(c) { CommonInit(); }
private:
	void CommonInit() {}
	int a_;
	double b_;
	int c_;
};

int main()
{
	X4 x4(1);
}
