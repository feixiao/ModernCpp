// ============================================================================
// 【说明】：演示私有构造函数导致对象无法在函数体内隐式构造时的 SFINAE 边界限制。
// 【重点】：
//   1. SFINAE 只作用于函数声明/签名替换阶段（即 Immediate Context）
//   2. 若函数签名匹配成功但在函数体内实例化时触发语义错误（如构造私有），仍会引发硬编译报错
// ============================================================================
template<class T>
T foo(T*)
{
	return T();
}

void foo(...) {}

class bar 
{
	bar() {};
};

int main()
{
	foo(static_cast<bar *>(nullptr));
}
