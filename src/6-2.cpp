// ============================================================================
// 【说明】：演示没有移动构造函数时，传统深拷贝/拷贝构造与赋值对临时对象的开销。
// 【重点】：
//   1. make_x() 返回临时纯右值
//   2. 传统 C++98 只能通过 const X& 绑定临时右值，并调用拷贝构造函数深拷贝
//   3. 引出 C++11 移动语义（Move Semantics）解决资源转移的需求
// ============================================================================
class X {
public:
	X() {}
	X(const X&) {}
	X& operator = (const X&) { return *this; }
};

X make_x()
{
	return X();
}

int main() 
{
	X x1;
	X x2(x1);
	X x3(make_x());
	x3 = make_x();
}
