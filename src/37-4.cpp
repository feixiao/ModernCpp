// ============================================================================
// 【说明】：演示 C++17 进一步放宽非类型模板参数支持无链接性静态局部变量的地址。
// 【重点】：
//   1. static const char str[] = "hello world"; Y<str> y;
//   2. 允许函数内的局部静态变量地址作为模板实参
// ============================================================================
template<const char *> struct Y {};
int main()
{
	static const char str[] = "hello world";
	Y<str> y;
}
