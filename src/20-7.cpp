// ============================================================================
// 【说明】：演示结构化绑定对类成员访问权限的限制规则（私有成员禁止绑定）。
// 【重点】：
//   1. 类包含私有成员 int a 时，直接使用 auto[x, y] = bt 将引发编译报错
//   2. 默认结构体解构规则要求所有非静态数据成员必须为 public
// ============================================================================
class BindTest {
	int a = 42;		// 私有成员变量
public:
	double b = 11.7;
};

int main()
{
	BindTest bt;
	auto[x, y] = bt;
}
