// ============================================================================
// 【说明】：演示 C++17 类模板实参推导（CTAD: Class Template Argument Deduction）。
// 【重点】：
//   1. foo v1(5, 6.8); 无需手写 foo<int, double>，编译器自动从构造函数实参推导类模板参数
//   2. 对比展示部分指定或空尖括号在 CTAD 规则下的合法性与错误用法
// ============================================================================
template<class T1, class T2>
struct foo
{
	foo(T1, T2) {}
};

int main()
{
	foo v1(5, 6.8);					// 编译成功
	foo<> v2(5, 6.8);				// 编译错误
	foo<int> v3(5, 6.8);			// 编译错误
	foo<int, double> v4(5, 6.8);	// 编译成功
}
