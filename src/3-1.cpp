// ============================================================================
// 【说明】：演示 C++17 引入的 auto 作为非类型模板参数（NTTP: Non-Type Template Parameter）。
// 【重点】：
//   1. template<auto N> 允许编译器自动推导模板非类型实参的类型（如 int、char）
//   2. 传统 C++ 中必须显式指定类型如 template<int N>
//   3. 注意 C++17 下浮点数（如 5.0）依然不能作为非类型模板参数（C++20 放宽了字面量结构支持）
// ============================================================================
#include <iostream>

template<auto N>
void f()
{
	std::cout << N << std::endl;
}
int main()
{
	f<5>();     // N为int类型
	f<'c'>();   // N为char类型
	// f<5.0>();   // 编译失败，模板参数不能为double
}
