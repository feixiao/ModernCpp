// ============================================================================
// 【说明】：演示 C++17 将 noexcept 正式纳入函数类型系统（Type System）的类型转换限制（编译错误）。
// 【重点】：
//   1. void(*fp)() noexcept 要求绑定的函数必须保证不抛异常
//   2. 普通未标注 noexcept 的函数 void foo() 不能赋值给带有 noexcept 的函数指针类型
// ============================================================================
void(*fp)() noexcept = nullptr;
void foo() {}

int main()
{
	fp = &foo;
}
