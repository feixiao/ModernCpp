// ============================================================================
// 【说明】：演示 C++17 折叠表达式（Fold Expressions）优雅实现一元右折叠求和。
// 【重点】：
//   1. return (args + ...);
//   2. 取代多层递归函数定义，编译器自动就地展开为 (arg1 + (arg2 + arg3))
// ============================================================================
#include <iostream>

template<class... Args>
auto sum(Args ...args)
{
	return (args + ...);
}

int main()
{
	std::cout << sum(1, 5.0, 11.7) << std::endl;
}
