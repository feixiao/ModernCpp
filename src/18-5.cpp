// ============================================================================
// 【说明】：演示 if 带初始化器在缓冲区输入与边界安全检查中的应用。
// 【重点】：
//   1. if (char buf[10]{0}; std::fgets(buf, 10, stdin))
//   2. 局部栈缓冲区随着读取完成自动销毁，无需在外部作用域提前开辟
// ============================================================================
#include <cstdio>
#include <string>

int main()
{
	std::string str;
	if (char buf[10]{0}; std::fgets(buf, 10, stdin)) {
		str += buf; 
	}
}
