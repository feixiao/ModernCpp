// ============================================================================
// 【说明】：演示 thread_local 变量地址与 static 变量地址在编译期常量表达式中的差异（编译错误）。
// 【重点】：
//   1. 静态全局变量 sv 地址在编译期确定，constexpr int *sp = &sv; 合法
//   2. thread_local 变量 tv 地址取决于运行时线程栈/TLS 偏移，不能用于 constexpr 指针初始化
// ============================================================================
thread_local int tv;
static int sv;

int main()
{
	constexpr int *sp = &sv;	// 编译成功，sv的地址在编译时确定
	constexpr int *tp = &tv;	// 编译失败，tv的地址在运行时确定
}
