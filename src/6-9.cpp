// ============================================================================
// 【说明】：演示函数按值返回局部形参（By-value Return）时的移动行为与自动右值转换。
// 【重点】：
//   1. 函数参数以值传递传入（X x）时，return x 会隐式视为右值表达式优先尝试调用移动构造
//   2. 终端打印输出 "move ctor"，展示编译器将命名局部返回值做移动转换
// ============================================================================
#include <iostream>

struct X {
	X() = default;
	X(const X&) = default;
	X(X&&) {
		std::cout << "move ctor";
	}
};

X f(X x) {
	return x;
}

int main() {
	X r = f(X{});
}
