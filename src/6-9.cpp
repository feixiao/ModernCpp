// ============================================================================
// 【说明】：演示函数按值返回局部形参（By-value Return）时的移动行为与自动右值转换。
// 【重点】：
//   1. 函数参数以值传递传入（X x）时，return x 会隐式视为右值表达式优先尝试调用移动构造
//   2. 终端打印输出 "move ctor"，展示编译器将命名局部返回值做移动转换
// ============================================================================
#include <iostream>


struct X {
	X() = default;
	X(const X&) = default;
	X(X&&) {
		std::cout << "move ctor";
	}
};

// 按值返回局部形参时，编译器会尝试将其视为右值，从而触发移动构造函数。
X f(X x) {
	return x;
}

int main() {
	// 调用 f(X{}) 时，临时对象 X{} 会被按值传入 f 的形参 x
	// 返回 x 时，编译器会尝试将其视为右值，从而触发移动构造函数
	X r = f(X{});
}
