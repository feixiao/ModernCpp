// ============================================================================
// 【说明】：演示 C++11 委托构造函数（Delegating Constructor）的基本语法。
// 【重点】：
//   1. 构造函数的初始化列表中调用同类的另一个构造函数（目标构造函数）
//   2. 如 X() : X(0, 0.) {}，避免编写多余的 CommonInit 辅助函数
// ============================================================================
class X
{
public:
	X() : X(0, 0.) {}
	X(int a) : X(a, 0.) {}
	X(double b) : X(0, b) {}
	X(int a, double b) : a_(a), b_(b) { CommonInit(); }
private:
	void CommonInit() {}
	int a_;
	double b_;
};
