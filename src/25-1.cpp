// ============================================================================
// 【说明】：演示 C++11 线程局部存储期（thread_local 存储期说明符）的基本声明方式。
// 【重点】：
//   1. thread_local static int i; 或 thread_local X b;
//   2. 保证每个线程拥有一份独立初始化的变量副本，生命周期贯穿该线程的运行始终
// ============================================================================
struct X {
	thread_local static int i;
};

thread_local X a;

int main()
{
	thread_local X b;
}
