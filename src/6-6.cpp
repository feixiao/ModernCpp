// ============================================================================
// 【说明】：演示右值引用与通用引用（转发引用）的区别：具体模板实例的右值引用不是通用引用。
// 【重点】：
//   1. void foo(std::vector<T>&&) 这里的形参虽然有 &&，但类型已被限定为 std::vector<T>
//   2. 它只能严格接受右值实参，传入左值 v 将导致编译报错
//   3. 只有类似 template<class T> void foo(T&&) 的未修饰模板形参才是通用引用
// ============================================================================
#include <vector>
template<class T>
void foo(std::vector<T> &&t) {}
int main()
{
	std::vector<int> v{ 1,2,3 };
	foo(v);							// 编译错误
}
