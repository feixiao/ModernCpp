// ============================================================================
// 【说明】：演示函数模板中形参推导类型优先于默认模板参数的决议规则。
// 【重点】：
//   1. template<class T = double> void foo(T t) {}
//   2. 传入整型实参 foo(5) 时，根据实参推导出 T 为 int，覆盖默认的 double
// ============================================================================
template<class T = double>
void foo(T t) {}

int main()
{
	foo(5);
}
