// ============================================================================
// 【说明】：演示传统 C++ 必须依靠额外大括号块限制变量作用域的对比写法。
// 【重点】：
//   1. 传统写法必须手写内嵌作用域 { bool b = foo(); if (b) ... }
//   2. 突显 18-1 中 C++17 语法的优雅与紧凑
// ============================================================================
#include <iostream>
bool foo()
{
	return true;
}
int main()
{
	{
		bool b = foo();
		if (b) {
			std::cout << std::boolalpha << "good! foo()=" << b << std::endl;
		}
	}
}
