// ============================================================================
// 【说明】：演示 C++11 非受限联合体（Unrestricted Union）中包含非平凡类型时的构造/析构限制。
// 【重点】：
//   1. 联合体成员包含 std::string/std::vector 等非平凡类型时，编译器默认删除 union 的构造与析构函数
//   2. 必须由开发者显式定义 U() 与 ~U()，否则会导致无法实例化对象
// ============================================================================
#include <iostream>
#include <string>
#include <vector>

union U
{
	U() {}		// 存在非平凡类型成员，必须提供构造函数
	~U() {}		// 存在非平凡类型成员，必须提供析构函数
	int x1;
	float x2;
	std::string x3;
	std::vector<int> x4;
};

int main()
{
	U u;
	u.x3 = "hello world";
	std::cout << u.x3;
}
