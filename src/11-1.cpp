// ============================================================================
// 【说明】：演示传统 C++ 联合体（union）的基本内存共享特性。
// 【重点】：
//   1. 联合体所有成员共享同一块内存空间，大小取决于最大成员
//   2. 向 float x2 写入数据会直接覆盖 int x1 内存位模式
// ============================================================================
#include <iostream>

union U
{
	int x1;
	float x2;
};

int main()
{
	U u;
	u.x1 = 5;
	std::cout << u.x1 << std::endl;
	std::cout << u.x2 << std::endl;

	u.x2 = 5.0;
	std::cout << u.x1 << std::endl;
	std::cout << u.x2 << std::endl;
}
