// ============================================================================
// 【说明】：演示通过 = delete 禁用特定类型的隐式转换构造（精确控制允许传入的参数类型）。
// 【重点】：
//   1. 提供 type(long long) 构造函数，但 explicit type(long) = delete;
//   2. 阻止传入 long 类型实参触发隐式或显式构造，防止非预期的类型转换
// ============================================================================
struct type
{
	type(long long) {}
	explicit type(long) = delete;
};
void foo(type) {}

int main()
{
	foo(type(58));
	foo(58);
}
