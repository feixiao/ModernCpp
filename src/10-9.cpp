// ============================================================================
// 【说明】：演示删除析构函数（~type() = delete）对对象创建与生命周期的影响。
// 【重点】：
//   1. 栈对象、静态对象在作用域退出时需要隐式调用析构函数，因此声明它们会直接编译失败
//   2. 堆对象（new type）允许分配，但在显式 delete var_ptr 时因无法调用析构函数而编译报错
// ============================================================================
struct type 
{
	~type() = delete;
};
type global_var;			// 编译失败，析构函数被删除无法隐式调用

int main()
{
	static type static_var;	// 编译失败，析构函数被删除无法隐式调用
	type auto_var;			// 编译失败，析构函数被删除无法隐式调用
	type *var_ptr = new type;
	delete var_ptr;			// 编译失败，析构函数被删除无法显式调用
}
