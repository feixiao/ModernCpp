// ============================================================================
// 【说明】：演示结构化绑定原生定长数组（C-style array）的用法。
// 【重点】：
//   1. int a[3]{ 1, 3, 5 }; auto[x, y, z] = a;
//   2. 绑定的变量个数必须与原生数组元素个数严格相等
// ============================================================================
#include <iostream>

int main()
{
	int a[3]{ 1, 3, 5 };
	auto[x, y, z] = a;
	std::cout << "[x, y, z]=[" 
		<< x << ", " 
		<< y << ", " 
		<< z << "]" << std::endl;
}
